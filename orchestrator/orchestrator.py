from llm.gemini_client import gemini_client
from router.router import RequestRouter
from rag.retrieval_pipeline import RAG
from crew.crew_manager import CrewManager


class Orchestrator:
    """
    Central orchestrator of the AI framework.

    Responsible for executing the pipeline steps produced
    by the RequestRouter.

    Supported pipelines:
        - LLM
        - RAG
        - CREW

    CREW can operate on:
        - GMAIL
        - CALENDAR
        - DRIVE
        - DOCS
        - MAPS
    """

    def __init__(self):

        self.llm = gemini_client
        self.router = RequestRouter()
        self.crew = CrewManager()

        # RAG instances are created separately for each
        # authenticated Google user.
        self.rag_instances = {}

    # -------------------------------------------------
    # Get User-Specific RAG
    # -------------------------------------------------

    def get_rag(self, google_email: str):

        if not google_email:
            raise ValueError(
                "Google email is required for RAG."
            )

        if google_email not in self.rag_instances:

            print(
                f"[DEBUG] Creating RAG instance for "
                f"{google_email}"
            )

            self.rag_instances[google_email] = RAG(
                user_google_email=google_email
            )

        return self.rag_instances[google_email]

    # -------------------------------------------------
    # Execute Request
    # -------------------------------------------------

    def execute(
        self,
        question: str,
        google_email: str,
    ) -> str:

        if not question:
            raise ValueError(
                "Question is required."
            )

        if not google_email:
            raise ValueError(
                "Google email is required."
            )

        # Router determines the complete execution plan.
        steps = self.router.determine_execution_plan(
            question
        )

        if not steps:
            raise RuntimeError(
                "Router returned an empty execution plan."
            )

        print(
            f"\n[DEBUG] Execution Plan: {steps}\n"
        )

        # This contains the output of the previous step.
        #
        # Initially it is the user's original question.
        current_result = question

        original_question = question

        # -------------------------------------------------
        # Execute steps sequentially
        # -------------------------------------------------

        for step_number, step in enumerate(steps):

            print(
                f"[DEBUG] Executing step "
                f"{step_number + 1}/{len(steps)}: "
                f"{step.pipeline}"
                f"{f', workspace={step.workspace}' if step.workspace else ''}"
                f"{f', task={step.task}' if step.task else ''}"
            )

            current_result = self.execute_step(
                step=step,
                question=current_result,
                original_question=original_question,
                google_email=google_email,
                step_number=step_number,
                total_steps=len(steps),
            )

            if current_result is None:
                raise RuntimeError(
                    f"Step {step_number + 1} "
                    f"produced no result."
                )

        if current_result is None:
            raise RuntimeError(
                "Execution produced no result."
            )

        return current_result

    # -------------------------------------------------
    # Execute Individual Pipeline
    # -------------------------------------------------

    def execute_step(
        self,
        step,
        question: str,
        original_question: str,
        google_email: str,
        step_number: int = 0,
        total_steps: int = 1,
    ) -> str:

        # =================================================
        # LLM
        # =================================================

        if step.pipeline == "llm":

            print(
                "[DEBUG] Executing LLM step"
            )

            # The TASK is the instruction generated by
            # the execution planner.
            task = step.task or "Process the result."

            # -------------------------------------------------
            # First LLM step
            #
            # There is no previous pipeline result.
            # The LLM should operate directly on the
            # original user request.
            # -------------------------------------------------

            if step_number == 0:

                prompt = f"""
You are an AI assistant executing a planned task.

Original user request:
{original_question}

Task:
{task}

Complete the task directly.

Do not invent information.
"""

            # -------------------------------------------------
            # Follow-up LLM step
            #
            # A previous pipeline has already produced a
            # result. The LLM must transform/extract/summarize
            # that result according to the TASK.
            # -------------------------------------------------

            else:

                prompt = f"""
You are an AI assistant executing one step
of a multi-step execution plan.

Original user request:
{original_question}

Current task:
{task}

Result produced by the previous pipeline:
{question}

Use the previous result as the input for the current task.

Perform ONLY the current task.

Do not repeat the previous pipeline operation.

Do not ask the user what they want to do with the result.

Only use information contained in the previous result.
Do not invent information.

Return the result of the current task clearly.
"""

            return self.llm.ask(prompt)

        # =================================================
        # RAG
        # =================================================

        elif step.pipeline == "rag":

            print(
                f"[DEBUG] Executing RAG step "
                f"for {google_email}"
            )

            rag = self.get_rag(
                google_email
            )

            task = step.task or (
                "Answer the user's question using "
                "the uploaded documents."
            )

            # -------------------------------------------------
            # First RAG step
            # -------------------------------------------------

            if step_number == 0:

                rag_question = f"""
The user originally asked:

{original_question}

RAG task:

{task}

Use the user's uploaded documents to answer
the original request.

Do not invent information.
Only use information supported by the uploaded
documents.
"""

            # -------------------------------------------------
            # RAG after another pipeline
            # -------------------------------------------------

            else:

                rag_question = f"""
The user originally asked:

{original_question}

Current RAG task:

{task}

A previous pipeline produced this result:

{question}

Use the previous result together with the user's
uploaded documents to complete the current task.

Perform ONLY the current RAG task.

Do not repeat the previous pipeline operation.

Do not invent information.
Only use information supported by the uploaded
documents and the previous pipeline result.
"""

            return rag.answer(
                question=rag_question,
                chat_history=""
            )

        # =================================================
        # CREW
        # =================================================

        elif step.pipeline == "crew":

            print(
                f"[DEBUG] Executing CREW step "
                f"{step_number + 1}/{total_steps} "
                f"(workspace={step.workspace})"
            )

            task = step.task

            if not task:
                raise ValueError(
                    "CREW execution step is missing TASK."
                )

            # -------------------------------------------------
            # First CREW step
            # -------------------------------------------------

            if step_number == 0:

                crew_question = f"""
Original user request:
{original_question}

Current task:
{task}

Perform ONLY this task.
"""

            # -------------------------------------------------
            # Sequential CREW step
            # -------------------------------------------------

            else:

                crew_question = f"""
Original user request:
{original_question}

Current task:
{task}

Result from the previous pipeline:
{question}

Use the previous pipeline result as input
for the current task.

Perform ONLY the current task.

Do not repeat the previous pipeline operation.

If the previous Maps result contains a place
with latitude and longitude, use those exact
coordinates for the current Maps operation.

Do not use only a place name when exact coordinates
are available.

Do not substitute another place with the same name.

Do not invent information.
"""

            result = self.crew.run(
                route=step.workspace,
                question=crew_question,
                google_email=google_email,
            )

            print("\n[DEBUG] CREW RESULT:")
            print(result)
            print("[DEBUG] END CREW RESULT\n")

            return result

        # =================================================
        # Unknown pipeline
        # =================================================

        else:

            raise ValueError(
                f"Unknown pipeline: {step.pipeline}"
            )